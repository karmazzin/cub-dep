const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const file = path.join(__dirname, '../src/3d/performance3d.js');
assert(fs.existsSync(file), 'adaptive performance controller must be implemented');
const context = { window: { CubDep: {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(file, 'utf8'), context);
const api = context.window.CubDep.performance3d;
const state = { worldMeta: { superOptimization: true }, ui: {} };
const baseline = api.getRenderPixelRatio3D(state, 1920, 1080, 2);
for (let i = 0; i < 100; i++) api.updateFrameBudget3D(state, 35, 25);
assert(state.performance3d.frameMs > 30, 'measure actual slow frames without hiding them');
assert.equal(api.getRenderPixelRatio3D(state, 1920, 1080, 2), baseline, 'load must not lower resolution');
const measured = state.performance3d.frameMs;
api.updateFrameBudget3D(state, 2500, 6);
assert.equal(state.performance3d.frameMs, measured, 'background pauses are ignored');
state.worldMeta.superOptimization = false;
api.updateFrameBudget3D(state, 40, 30);
assert.equal(state.performance3d, null);
assert.equal(api.getRenderPixelRatio3D(state, 1920, 1080, 2), baseline);
console.log('performance monitoring preserves image quality');
