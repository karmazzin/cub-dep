const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const file = path.join(__dirname, '../src/3d/performance3d.js');
assert(fs.existsSync(file), 'adaptive performance controller must be implemented');
const context = { window: { CubDep: {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(file, 'utf8'), context);
const api = context.window.CubDep.performance3d;
const state = { worldMeta: { superOptimization: true }, ui: {} };
for (let i = 0; i < 120; i++) api.updateFrameBudget3D(state, 1000 / 60, 6);
assert.equal(api.getQualityProfile3D(state).level, 0, 'stable 60 FPS must not lower quality');
api.updateFrameBudget3D(state, 2500, 6);
assert.equal(api.getQualityProfile3D(state).level, 0, 'returning from a background tab must not lower quality');
for (let i = 0; i < 100; i++) api.updateFrameBudget3D(state, 35, 25);
const low = api.getQualityProfile3D(state);
assert(low.level > 0, 'sustained slow frames must reduce quality');
assert(low.resolutionScale < 1 && low.distantRadius < 6 && low.sampleStep > 4);
assert(api.getRenderPixelRatio3D(state, 1920, 1080, 2) < 1, 'GPU resolution must fall under load');
for (let i = 0; i < 1200; i++) api.updateFrameBudget3D(state, 1000 / 60, 4);
assert.equal(api.getQualityProfile3D(state).level, 0, 'sustained spare time should recover quality slowly');
assert.equal(api.getQualityProfile3D(state).distantRadius, low.distantRadius, 'FPS recovery must not repeatedly reload the distant horizon');
assert.equal(api.getQualityProfile3D(state).sampleStep, low.sampleStep, 'FPS recovery must not switch distant blocks back to detailed shapes');
state.worldMeta.superOptimization = false;
api.updateFrameBudget3D(state, 40, 30);
assert.equal(api.getRenderPixelRatio3D(state, 1920, 1080, 2), 1.5, 'disabling must restore normal pixel ratio');
state.worldMeta.superOptimization = true;
assert.equal(api.getQualityProfile3D(state).level, 0, 're-enabling must start with a fresh budget');
assert(api.getRenderPixelRatio3D(state, 3840, 2160, 2) <= 1 / 3, 'baseline optimization must cap the 3D image at 720p');
console.log('adaptive performance smoke tests passed');
