const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const file = path.join(__dirname, '../src/3d/performance3d.js');
assert(fs.existsSync(file), 'adaptive performance controller must be implemented');
const context = { window: { CubDep: {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(file, 'utf8'), context);
const api = context.window.CubDep.performance3d;
const state = { worldMeta: { superOptimization: true }, ui: {} };
const baseline = api.getRenderPixelRatio3D(state, 1920, 1080, 2);
for (let i = 0; i < 100; i++) api.updateFrameBudget3D(state, 35, 25);
assert(state.performance3d.frameMs > 30, 'measure actual slow frames without hiding them');
assert.equal(api.getRenderPixelRatio3D(state, 1920, 1080, 2), baseline, 'load must not lower resolution');
const measured = state.performance3d.frameMs;
api.updateFrameBudget3D(state, 2500, 6);
assert.equal(state.performance3d.frameMs, measured, 'background pauses are ignored');
state.worldMeta.superOptimization = false;
api.updateFrameBudget3D(state, 40, 30);
assert.equal(state.performance3d, null);
assert.equal(api.getRenderPixelRatio3D(state, 1920, 1080, 2), baseline);
console.log('performance monitoring preserves image quality');

context.window.innerWidth = 390;
context.window.innerHeight = 844;
context.window.matchMedia = () => ({ matches: true });
state.worldMeta.superOptimization = true;
const phoneRatio = () => api.getRenderPixelRatio3D(state, 390, 844, 3);
const initial = phoneRatio();
assert(initial <= 1, 'mobile optimization should immediately reduce pixel work');
for (let i = 0; i < 200; i++) api.updateFrameBudget3D(state, 33, 8);
assert(phoneRatio() < initial, 'sustained slow frames should lower mobile resolution');
assert(phoneRatio() >= 0.5, 'resolution must remain usable');
const low = phoneRatio();
api.updateFrameBudget3D(state, 5000, 4);
assert.equal(phoneRatio(), low, 'return from background must not change quality');
for (let i = 0; i < 360; i++) api.updateFrameBudget3D(state, 1000 / 60, 7);
assert(phoneRatio() > low, 'stable 60 FPS should cautiously recover quality');
const recovered = phoneRatio();
for (let i = 0; i < 60; i++) api.updateFrameBudget3D(state, i % 2 ? 18 : 16, 8);
assert.equal(phoneRatio(), recovered, 'small timing jitter must not cause resolution changes');
assert(api.getMobileWorkBudget3D(state, 7) <= 2, 'phone chunk work must yield sooner');
state.worldMeta.superOptimization = false;
assert.equal(phoneRatio(), 1.5, 'disabling optimization immediately restores resolution');
assert.equal(api.getMobileWorkBudget3D(state, 7), 7);
api.updateFrameBudget3D(state, 16, 8);
assert.equal(state.performance3d, null);
context.window.matchMedia = () => ({ matches: false });
context.window.innerWidth = 1280;
state.worldMeta.superOptimization = true;
assert.equal(api.getRenderPixelRatio3D(state, 1280, 720, 2), 1.5, 'desktop graphics stay unchanged');
assert.equal(api.getMobileWorkBudget3D(state, 7), 7);
console.log('mobile adaptive resolution, recovery, and work budgets passed');
